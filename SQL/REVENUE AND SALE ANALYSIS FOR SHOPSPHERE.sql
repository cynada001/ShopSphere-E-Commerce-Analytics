--============================================================
-- GEOGRAPHIC ANALYSIS
-- REVENUE CONTRIBUTION BY COUNTRY
--============================================================

WITH COUNTRY_REVENUE AS (
    SELECT
        TRIM([COUNTRY]) AS COUNTRY,
        SUM([SALES AMOUNT]) AS TOTAL_REVENUE
    FROM [OLE DB Destination]
    GROUP BY
        TRIM([COUNTRY])
),

TOTAL_REVENUE AS (
    SELECT
        SUM(TOTAL_REVENUE) AS COMPANY_REVENUE
    FROM COUNTRY_REVENUE
)

SELECT
    CR.COUNTRY,
    CR.TOTAL_REVENUE,

    ROUND(
        CAST(CR.TOTAL_REVENUE AS DECIMAL(18,2))
        / NULLIF(TR.COMPANY_REVENUE, 0) * 100,
        2
    ) AS REVENUE_CONTRIBUTION_PCT

FROM COUNTRY_REVENUE CR

CROSS JOIN TOTAL_REVENUE TR

ORDER BY
    REVENUE_CONTRIBUTION_PCT DESC;


--============================================================
