-- ============================================================
-- TOP & BOTTOM GEOGRAPHIC MARKETS
-- STATE LEVEL
-- ============================================================

WITH STATE_REVENUE AS (
    SELECT
        TRIM([STATE]) AS STATE,
        SUM([SALES AMOUNT]) AS TOTAL_REVENUE
    FROM [OLE DB Destination]
    GROUP BY
        TRIM([STATE])
),

RANKED_STATES AS (
    SELECT
        STATE,
        TOTAL_REVENUE,

        RANK() OVER (
            ORDER BY TOTAL_REVENUE DESC
        ) AS REVENUE_RANK_DESC,

        RANK() OVER (
            ORDER BY TOTAL_REVENUE ASC
        ) AS REVENUE_RANK_ASC

    FROM STATE_REVENUE
)

SELECT
    STATE,
    TOTAL_REVENUE,
    REVENUE_RANK_DESC,
    REVENUE_RANK_ASC,

    CASE
        WHEN REVENUE_RANK_DESC <= 10
            THEN 'TOP MARKET'

        WHEN REVENUE_RANK_ASC <= 10
            THEN 'BOTTOM MARKET'

        ELSE 'MID-TIER MARKET'
    END AS MARKET_CLASSIFICATION

FROM RANKED_STATES

ORDER BY
    TOTAL_REVENUE DESC;


